) {
    /** @throws IllegalStateException for an unknown key, which is a programming error, not user input. */
    operator fun get(key: String): String = values[key] ?: error("No export string '$key' for '$language'")

    /** Translated label of a checklist key ([app.doorprints.shared.model.Checklist.keys]); the key itself if new. */
    fun check(key: String): String = values["check.$key"] ?: key

    fun status(name: String): String = values["status.$name"] ?: name

    fun source(name: String): String = values["source.$name"] ?: name

    fun priceType(name: String?): String = values["priceType.${name ?: "RENT"}"] ?: (name ?: "")

    internal val keys: Set<String> get() = values.keys

