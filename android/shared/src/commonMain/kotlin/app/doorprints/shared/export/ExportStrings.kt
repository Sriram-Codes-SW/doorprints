/**
 * The words that appear **inside** an exported copy, in the export language (docs/11 section 5.2: "language
 * (en/hi/ta/te)" is an export option, separate from the app's own language).
 *
 * They live here, not in the apps' own string catalogues (`res/values-hi/strings.xml` and the web's i18n
 * files), for three reasons:
 *  * the export language is chosen per export, so a copy in Tamil must be possible while the phone runs in English;
 *  * `commonMain` has no access to Android resources, and the same table has to drive the web exporters;
 *  * golden tests can only pin the output if the headings are part of the pinned code.
 *
 * The house-status and checklist wordings are copied from the app's `strings.xml` (and the web's catalogues) on
 * purpose, so an exported table reads like the screen it came from. Values that are shown to the user in the app
 * UI stay in `strings.xml`; only export-document text belongs here.
 *
 * Every language must define the same keys; `ExportStringsTest` fails if one is missing or spare.
