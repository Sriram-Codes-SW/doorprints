export function readKinds(root = ROOT) {
  return KINDS.map((id) => {
    const file = JSON.parse(fs.readFileSync(path.join(root, 'docs/schemas/kinds', `${id}.json`), 'utf8'));
    if (file.id !== id) throw new Error(`${id}.json has the id ${file.id}`);
    return { id, words: file.words };
  });
}

const q = (s) => (s === null || s === undefined ? 'null' : `'${s}'`);
const qk = (s) => (s === null || s === undefined ? 'null' : `"${s}"`);

export function webSource(kinds) {
  const ids = Object.keys(kinds[0].words);
  for (const k of kinds) {
    if (JSON.stringify(Object.keys(k.words)) !== JSON.stringify(ids)) throw new Error(`${k.id}.json does not hold the house's ids in the house's order`);
  }
  const rows = ids
    .filter((id) => kinds.some((k) => k.words[id].web))
    .map((id) => `  [${[q(id), ...kinds.map((k) => q(k.words[id].web))].join(', ')}],`);
  return `${HEADER}
// GENERATED by tools/gen-kind-words.mjs from docs/schemas/kinds/*.json \`words\` (kinds PR 31, docs/03 section 18.25). Do not edit:
// change the kind file and run \`node tools/gen-kind-words.mjs\`; \`--check\` (tools/check.sh, CI) fails when this file is stale.
import type { TKey } from '../i18n/en';

/** The kinds that have a column below, the baseline first; a kind not listed reads the first column (the house's words). */
export const KIND_WORD_KINDS: readonly string[] = [${kinds.map((k) => q(k.id)).join(', ')}];

/** One word: its id, then the website's translation key in each kind of {@link KIND_WORD_KINDS} (\`null\`: the website has no such word there). */
export type KindWordRow = readonly [id: string, ...keys: (TKey | null)[]];

/** Every word the website has, in the kind files' order. */
export const KIND_WORD_ROWS: readonly KindWordRow[] = [
${rows.join('\n')}
];
`;
}

export function kotlinSource(kinds) {
  const ids = Object.keys(kinds[0].words);
  const maps = kinds
    .map((k) => {
      const entries = ids.map((id) => `"${id}" to ${qk(k.words[id].android)}`);
      const lines = [];
      for (let i = 0; i < entries.length; i += 3) lines.push(`            ${entries.slice(i, i + 3).join(', ')},`);
      return `        "${k.id}" to table(\n${lines.join('\n')}\n        ),`;
    })
    .join('\n');
  const idLines = [];
  for (let i = 0; i < ids.length; i += 6) idLines.push(`        ${ids.slice(i, i + 6).map((id) => `"${id}"`).join(', ')},`);
  return `${HEADER}
package app.doorprints.shared.model

// GENERATED by tools/gen-kind-words.mjs from docs/schemas/kinds/*.json \`words\` (kinds PR 31, docs/03 section 18.25). Do not edit:
// change the kind file and run \`node tools/gen-kind-words.mjs\`; \`--check\` (tools/check.sh, CI) fails when this file is stale.

/** The Android keys of the kind files' \`words\`, one map per kind (null: the phone shows no text there). [KindWordKeys] reads it. */
internal object KindWordData {
    /** The ids of \`words\` in the schema, in its order. */
    val IDS: List<String> = listOf(
${idLines.join('\n')}
    )

    private fun table(vararg keys: Pair<String, String?>): Map<String, String?> {
        check(keys.map { it.first } == IDS) { "the words are not the schema's ids, in order" }
        return keys.toMap()
    }

    /** Kind id to its keys; the house's first. */
    val BY_KIND: Map<String, Map<String, String?>> = linkedMapOf(
${maps}
    )
}
`;
}

export function outputs(root = ROOT) {
  const kinds = readKinds(root);
  return [
    [WEB_OUT, webSource(kinds)],
    [KOTLIN_OUT, kotlinSource(kinds)],
  ];
}

function main() {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [rel, text] of outputs()) {
    const file = path.join(ROOT, rel);
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (have === text) continue;
    if (check) {
      console.error(`${rel} is stale: run node tools/gen-kind-words.mjs`);
      stale++;
    } else {
      fs.writeFileSync(file, text);
      console.log(`wrote ${rel}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log('kind words: the generated files match the kind files');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
