const EXPORT_DICTS: Readonly<Record<Lang, ExportDict>> = {
  en: EXPORT_EN,
  hi: EXPORT_HI,
  ta: EXPORT_TA,
  te: EXPORT_TE,
};

/**
 * Reader for one export language. `get` throws on an unknown key, because that is a programming error rather
 * than user input; the `status` / `source` / `priceType` / `check` lookups fall back to the raw key, because
 * those come from stored data a newer app version may have written (a custom checklist criterion, Sprint 4b).
 */
export class ExportStrings {
  readonly language: Lang;
  private readonly values: ExportDict;

  private constructor(language: Lang, values: ExportDict) {
    this.language = language;
    this.values = values;
  }

  static of(language: Lang): ExportStrings {
    return new ExportStrings(language, EXPORT_DICTS[language] ?? EXPORT_EN);
  }

  get(key: ExportStringKey): string {
    const value = this.values[key];
    if (value === undefined) throw new Error(`No export string '${key}' for '${this.language}'`);
    return value;
  }

  /** Translated label of a checklist key; the key itself when this version does not know it. */
  check(key: string): string {
    return this.lookup(`check.${key}`) ?? key;
  }

  status(name: string): string {
    return this.lookup(`status.${name}`) ?? name;
  }

  source(name: string): string {
    return this.lookup(`source.${name}`) ?? name;
  }

  priceType(name: string | null | undefined): string {
    return this.lookup(`priceType.${name ?? 'RENT'}`) ?? name ?? '';
  }

  private lookup(key: string): string | undefined {
    return (this.values as Readonly<Record<string, string>>)[key];
  }
}

export const ALL_EXPORT_STRINGS: readonly ExportStrings[] = (['en', 'hi', 'ta', 'te'] as const).map((l) =>
  ExportStrings.of(l),
);
