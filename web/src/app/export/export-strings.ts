/**
 * The words that appear **inside** an exported table, in the export language.
 *
 * This is the TypeScript half of `android/shared/src/commonMain/kotlin/com/househunt/shared/export/
 * ExportStrings.kt`: the same keys, the same wordings, in the same order. The two files are a contract, like
 * `sync-rules.ts` and `SyncRules.kt`: a change on one side that is not made on the other shows up as a failing
 * golden test rather than as two apps quietly writing different files.
 *
 * Why these are not the app's own i18n catalogue (`i18n/en.ts`), which is the question a reader will have:
 *  * the export language is chosen **per export**, so a copy in Tamil has to be possible while the app itself is
 *    being used in English — `ExportOptions.lang`, not `TranslationService.lang`;
 *  * `commonMain` on the Android side cannot read Android resources, and the same table drives both apps;
 *  * a golden test can only pin the output if the headings are part of the pinned code.
 *
 * `export-strings.spec.ts` checks that all four languages carry exactly these keys.
 */

